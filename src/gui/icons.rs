    fn svg(self) -> &'static [u8] {
        static CACHE: OnceLock<Mutex<HashMap<Icon, &'static [u8]>>> = OnceLock::new();
        let mut cache = CACHE.get_or_init(Default::default).lock().unwrap();
        cache.entry(self).or_insert_with(|| {
            let svg = format!(
                r##"<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" width="96" height="96" fill="#ffffff"><path d="{}"/></svg>"##,
                self.path()
            );
            Box::leak(svg.into_bytes().into_boxed_slice())
        })
    }

    pub fn image(self, size: f32, color: Color32) -> egui::Image<'static> {
        egui::Image::from_bytes(format!("bytes://icon/{self:?}.svg"), self.svg())
            .fit_to_exact_size(Vec2::splat(size))
            .tint(color)
    }

    pub fn paint(self, ui: &egui::Ui, rect: Rect, color: Color32) {
        self.image(rect.width(), color).paint_at(ui, rect);
    }

    /// Adds the icon as a widget.
    pub fn show(self, ui: &mut egui::Ui, size: f32, color: Color32) -> egui::Response {
        ui.add(self.image(size, color))
    }
